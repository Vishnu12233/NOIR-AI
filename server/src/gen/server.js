// Builds the generated app's server.js (zero-dependency Node HTTP server).
import { fieldDefs } from './schema.js';

export function buildSchemaJs(spec) {
  const out = ['// Data model — generated by NOIR. Edit the spec in NOIR to change it.', 'export const SCHEMA = ['];
  for (const t of spec.tables) {
    out.push('  { table: ' + JSON.stringify(t.table) + ', label: ' + JSON.stringify(t.label) + ',');
    out.push('    fields: ' + JSON.stringify(fieldDefs(t)) + ',');
    out.push('    search: ' + JSON.stringify(t.search || []) + ',');
    out.push('    fk: ' + JSON.stringify(t.fk || []) + ' },');
  }
  out.push('];');
  return out.join('\n');
}

export function buildSeedJs(spec, tables) {
  const out = ['// Sample data — generated by NOIR. Used when the app runs on its built-in file', '// database (no DATABASE_URL configured).', 'export const SEED = ['];
  for (const key of Object.keys(spec.seed || {})) {
    if (!tables.some((t) => t.table === key)) continue;
    out.push('  { table: ' + JSON.stringify(key) + ', rows: ' + JSON.stringify(spec.seed[key]) + ' },');
  }
  out.push('];');
  return out.join('\n');
}

function clientFields(t) {
  return fieldDefs(t).filter((f) => !f.private);
}

export function buildMetaConst(spec) {
  const tables = spec.tables.map((t) => ({
    table: t.table,
    label: t.label,
    client: t.client ?? (t.table === 'users' ? 'admin' : true),
    hidden: !!t.hidden,
    fields: clientFields(t),
    search: t.search || [],
  }));
  const meta = {
    name: spec.name,
    tagline: spec.tagline || '',
    brand: spec.brand || 'NOIR',
    stack: spec.stack || '',
    default_theme: spec.default_theme || 'dark',
    landing: !!spec.landing,
    main: spec.main || (spec.tables[0] && spec.tables[0].table) || 'items',
    auth: !!spec.auth,
    detail: !!spec.detail,
    nav: (spec.nav || []),
    tables,
    features: (spec.features || []).map((f) => (typeof f === 'string' ? f : f.key)),
    routes: spec.routes || ['home'],
    sample_data: !!spec.seed_enabled,
    db: 'file-or-postgres',
  };
  return 'export const META = ' + JSON.stringify(meta, null, 1).split('\n').join('\n') + ';\n';
}

const JS_STRING = (s) => JSON.stringify(s);

export function buildServerJs(spec, hasAuth, feats) {
  const L = [];
  const guardedTables = spec.tables.filter((t) => t.guarded || t.table === 'users').map((t) => t.table);
  L.push(`// ${spec.name} — HTTP API + static server. Generated by NOIR.
// Zero external runtime dependencies. Data: built-in JSON file DB, or PostgreSQL
// automatically when the DATABASE_URL environment variable is set.
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { ok, fail, readBody, hashPw, verifyPw } from './lib/utils.js';
import { defineTables, store } from './lib/store.js';
import { defineTables as definePgTables, store as pgStore, connect as pgConnect, hasPg as pgAvailable } from './lib/pg.js';
import { SCHEMA } from './db/schema.js';
import { SEED } from './db/seed.js';
import { META } from './meta.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = __dirname;
const SRC = path.join(ROOT, 'src');
const DATA = path.join(ROOT, 'data');
const PORT = Number(process.env.PORT || 3210);
const HOST = process.env.HOST || '127.0.0.1';

// ---- pick storage backend ----
const USE_PG = pgAvailable();
if (USE_PG) {
  definePgTables(SCHEMA);
  await pgConnect().catch((e) => { console.error('[db] PostgreSQL unavailable:', e.message); process.exit(1); });
} else {
  defineTables(SCHEMA);
  store.seed(SEED.length ? SEED : null);
}
const DB = USE_PG ? pgStore : store;

const fieldOf = (table, key) => (SCHEMA.find((s) => s.table === table) || { fields: [] }).fields.find((f) => f.key === key);
const hiddenKeys = (table) => (SCHEMA.find((s) => s.table === table) || { fields: [] }).fields.filter((f) => f.private).map((f) => f.key);
const clean = (table, row) => { if (!row) return row; const out = { ...row }; for (const k of hiddenKeys(table)) delete out[k]; return out; };
`);
  if (hasAuth) {
    L.push(`
// ---- auth session helpers ----
const COOKIE = 'noir_session';
const SESSIONS = new Map();
const readToken = (req) => {
  const h = req.headers['x-auth-token']; if (h) return h;
  const c = (req.headers.cookie || '').split(';').map((x) => x.trim()).find((x) => x.startsWith(COOKIE + '='));
  return c ? c.slice(COOKIE.length + 1) : null;
};
const currentUser = async (req) => {
  const tok = readToken(req); const id = tok && SESSIONS.get(tok);
  if (!id) return null;
  return DB.get('users', id);
};
const setSession = (res, userId) => { const token = crypto.randomBytes(24).toString('hex'); SESSIONS.set(token, userId); res.setHeader('set-cookie', COOKIE + '=' + token + '; Path=/; HttpOnly; SameSite=Lax; Max-Age=' + 60 * 60 * 24 * 14); };
const clearSession = (res) => { res.setHeader('set-cookie', COOKIE + '=; Path=/; Max-Age=0'); };
async function findUserByEmail(email) {
  const rows = await DB.list('users');
  return rows.find((u) => String(u.email).toLowerCase() === String(email || '').toLowerCase()) || null;
}
`);
  }
  L.push(`
const GUARDED = new Set(${JSON.stringify(guardedTables)});

async function handleApi(req, res, pathname, query) {
  const method = req.method;
  const m = pathname.split('/').filter(Boolean);
  if (!m.length || m[0] !== 'api') return false;

  if (m[1] === 'health') { ok(res, { status: 'ok', time: new Date().toISOString(), db: USE_PG ? 'postgres' : 'file', app: ${JS_STRING(spec.name)} }); return true; }
  if (m[1] === 'meta') { ok(res, META); return true; }
  if (m[1] === 'summary') {
    const out = {};
    for (const s of SCHEMA) out[s.table] = (await DB.list(s.table)).length;
    ok(res, out); return true;
  }
`);
  if (hasAuth) {
    L.push(`
  // ---- auth ----
  if (m[1] === 'auth' && m.length >= 3) {
    const a = m[2];
    if (a === 'signup' && method === 'POST') {
      const b = await readBody(req); if (!b) { fail(res, 400, 'Invalid JSON body'); return true; }
      if (!b.email || !String(b.password || '').length || String(b.password).length < 6) { fail(res, 400, 'Password must be at least 6 characters'); return true; }
      if (await findUserByEmail(b.email)) { fail(res, 409, 'An account with this email already exists'); return true; }
      const row = await DB.insert('users', { email: String(b.email).toLowerCase(), name: String(b.name || '').slice(0, 120) || String(b.email).split('@')[0], password_hash: await hashPw(String(b.password)), role: 'user', verified: 'yes' });
      setSession(res, row.id); ok(res, clean('users', row), 201); return true;
    }
    if (a === 'login' && method === 'POST') {
      const b = await readBody(req); if (!b) { fail(res, 400, 'Invalid JSON body'); return true; }
      const u = await findUserByEmail(b.email);
      if (!u || !(await verifyPw(String(b.password || ''), u.password_hash))) { fail(res, 401, 'Incorrect email or password', 'BAD_CREDENTIALS'); return true; }
      setSession(res, u.id); ok(res, clean('users', u)); return true;
    }
    if (a === 'logout' && method === 'POST') { const tok = readToken(req); if (tok) SESSIONS.delete(tok); clearSession(res); ok(res, { signed_out: true }); return true; }
    if (a === 'me' && method === 'GET') { const u = await currentUser(req); if (!u) { fail(res, 401, 'Not signed in', 'UNAUTHENTICATED'); return true; } ok(res, clean('users', u)); return true; }
    if (a === 'me' && method === 'PATCH') {
      const u = await currentUser(req); if (!u) { fail(res, 401, 'Not signed in', 'UNAUTHENTICATED'); return true; }
      const b = await readBody(req) || {};
      const patch = {};
      if (typeof b.name === 'string' && b.name.trim()) patch.name = b.name.trim().slice(0, 120);
      const row = await DB.update('users', u.id, patch);
      ok(res, clean('users', row)); return true;
    }
    if (a === 'password' && method === 'POST') {
      const u = await currentUser(req); if (!u) { fail(res, 401, 'Not signed in', 'UNAUTHENTICATED'); return true; }
      const b = await readBody(req) || {};
      if (!b.next || String(b.next).length < 6) { fail(res, 400, 'New password must be at least 6 characters'); return true; }
      if (!(await verifyPw(String(b.current || ''), u.password_hash))) { fail(res, 401, 'Current password is incorrect'); return true; }
      await DB.update('users', u.id, { password_hash: await hashPw(String(b.next)) });
      ok(res, { changed: true }); return true;
    }
    return true;
  }
`);
  }
  // ---- generic REST per table ----
  for (const t of spec.tables) {
    const table = t.table;
    const guarded = guardedTables.includes(table);
    const searchKeys = (t.search && t.search.length ? t.search : (fieldDefs(t).filter((f) => !f.noAuto && !f.private).map((f) => f.key).slice(0, 4)));
    const hasUserId = fieldDefs(t).some((f) => f.key === 'user_id');
    const hasAuthor = fieldDefs(t).some((f) => f.key === 'author');
    L.push(`
  if (m[1] === ${JS_STRING(table)}) {
    ${guarded ? `const u = await currentUser(req); if (!u || u.role !== 'admin') { fail(res, 403, 'Admin access required for ${table}', 'FORBIDDEN'); return true; }` : ''}
    if (method === 'GET' && m.length === 2) {
      let rows = await DB.list(${JS_STRING(table)});
      const q = query.get('q');
      if (q) {
        const keys = ${JSON.stringify(searchKeys)};
        rows = rows.filter((r) => keys.some((k) => String(r[k] ?? '').toLowerCase().includes(String(q).toLowerCase())));
      }
      const sort = query.get('sort'); const dir = query.get('order') || 'desc';
      if (sort) rows.sort((a, b) => String(a[sort] ?? '').localeCompare(String(b[sort] ?? '')));
      if (dir === 'desc') rows.reverse();
      if (query.get('fmt') === 'csv') {
        const cols = ${JSON.stringify(fieldDefs(t).filter((f) => !f.hidden && !f.private).map((f) => f.key))};
        const escC = (v) => '"' + String(v ?? '').replace(/"/g, '""') + '"';
        res.setHeader('content-type', 'text/csv');
        res.setHeader('content-disposition', 'attachment; filename="${table}.csv"');
        res.end([cols.map(escC).join(',')].concat(rows.map((r) => cols.map((c) => escC(r[c])).join(','))).join('\\n'));
        return true;
      }
      ok(res, { items: rows.map((r) => clean(${JS_STRING(table)}, r)), total: rows.length, table: ${JS_STRING(table)} }); return true;
    }
    if (method === 'GET' && m.length === 3) {
      const row = await DB.get(${JS_STRING(table)}, m[2]);
      if (!row) { fail(res, 404, 'Not found'); return true; }
      ok(res, clean(${JS_STRING(table)}, row)); return true;
    }
    if (method === 'POST' && m.length === 2) {
      const body = await readBody(req); if (!body) { fail(res, 400, 'Invalid JSON body'); return true; }
      ${hasAuth && !guarded ? `const me = await currentUser(req);` : ''}
      ${hasUserId && hasAuth && !guarded ? `if (me && !body.user_id) body.user_id = String(me.id);` : ''}
      ${hasAuthor && hasAuth && !guarded ? `if (me && !body.author) body.author = me.name || me.email;` : ''}
      try { const row = await DB.insert(${JS_STRING(table)}, body); ok(res, clean(${JS_STRING(table)}, row), 201); } catch (e) { fail(res, 409, 'Could not create: ' + (e.message || e)); } return true;
    }
    if (method === 'PATCH' && m.length === 3) {
      const body = await readBody(req); if (!body) { fail(res, 400, 'Invalid JSON body'); return true; }
      const row = await DB.update(${JS_STRING(table)}, m[2], body);
      if (!row) { fail(res, 404, 'Not found'); return true; }
      ok(res, clean(${JS_STRING(table)}, row)); return true;
    }
    if (method === 'DELETE' && m.length === 3) {
      const gone = await DB.remove(${JS_STRING(table)}, m[2]);
      if (!gone) { fail(res, 404, 'Not found'); return true; }
      ok(res, { deleted: true }); return true;
    }
    return true;
  }
`);
  }
  if (feats.includes('ai_chat')) {
    L.push(`
  if (m[1] === 'chat' && method === 'POST') {
    const body = await readBody(req); if (!body) { fail(res, 400, 'Invalid JSON body'); return true; }
    const key = process.env.OPENAI_API_KEY || process.env.NOIR_AI_API_KEY || process.env.ANTHROPIC_API_KEY || process.env.GOOGLE_API_KEY;
    if (!key) { fail(res, 503, 'AI provider is not configured. Add a provider key in NOIR → Environment to enable this chat.', 'REQUIRES_CONFIG'); return true; }
    try {
      const base = process.env.NOIR_AI_BASE || 'https://api.openai.com/v1';
      const model = process.env.NOIR_AI_MODEL || 'gpt-4o-mini';
      const msgs = Array.isArray(body.messages) ? body.messages.slice(-16) : [];
      const upstream = await fetch(base.replace(/\\/$/, '') + '/chat/completions', {
        method: 'POST',
        headers: { 'content-type': 'application/json', authorization: 'Bearer ' + key },
        body: JSON.stringify({ model, messages: msgs }),
      });
      const j = await upstream.json();
      if (!upstream.ok) throw new Error((j.error && j.error.message) || ('Provider returned ' + upstream.status));
      const reply = (j.choices && j.choices[0] && j.choices[0].message && j.choices[0].message.content) || '(empty reply)';
      ok(res, { reply, model, usage: j.usage || null, provider: 'openai-compatible' }); return true;
    } catch (e) { fail(res, 502, 'AI provider error: ' + (e.message || e), 'AI_ERROR'); return true; }
  }
`);
  }
  if (feats.includes('payments')) {
    L.push(`
  if (m[1] === 'checkout' && method === 'POST') {
    const body = await readBody(req); if (!body) { fail(res, 400, 'Invalid JSON body'); return true; }
    const key = process.env.STRIPE_SECRET_KEY;
    if (!key) { fail(res, 503, 'Payments are not configured. Add STRIPE_SECRET_KEY in NOIR → Environment to enable checkout.', 'REQUIRES_CONFIG'); return true; }
    try {
      const form = new URLSearchParams({ mode: 'payment', 'line_items[0][quantity]': '1' });
      if (body.price_id) form.set('line_items[0][price]', String(body.price_id));
      else if (body.amount) { form.set('line_items[0][price_data][currency]', 'usd'); form.set('line_items[0][price_data][unit_amount]', String(Math.round(Number(body.amount) * 100))); form.set('line_items[0][price_data][product_data][name]', String(body.name || 'Purchase')); }
      const success = body.success_url || ('http://' + HOST + ':' + PORT + '/');
      form.set('success_url', success);
      const up = await fetch('https://api.stripe.com/v1/checkout/sessions', { method: 'POST', headers: { authorization: 'Bearer ' + key, 'content-type': 'application/x-www-form-urlencoded' }, body: form });
      const j = await up.json();
      if (!up.ok) throw new Error((j.error && j.error.message) || ('Stripe returned ' + up.status));
      ok(res, { url: j.url, session_id: j.id, provider: 'stripe' }); return true;
    } catch (e) { fail(res, 502, 'Payment provider error: ' + (e.message || e), 'PAYMENT_ERROR'); return true; }
  }
`);
  }
  L.push(`  return false;
}

// ---- static + SPA ----
const MIME = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif', '.webp': 'image/webp', '.ico': 'image/x-icon', '.txt': 'text/plain', '.md': 'text/markdown', '.csv': 'text/csv', '.woff2': 'font/woff2', '.pdf': 'application/pdf' };
function joinSafe(base, p) { const target = path.normalize(path.join(base, p)); return target.startsWith(base) ? target : null; }
function serveStatic(req, res, pathname) {
  let p = null;
  if (pathname === '/' ) p = path.join(SRC, 'index.html');
  else if (pathname.startsWith('/uploads/')) p = joinSafe(path.join(DATA, 'uploads'), pathname.slice(9));
  else p = joinSafe(SRC, pathname.slice(1));
  if (!p || !fs.existsSync(p) || !fs.statSync(p).isFile()) {
    if (pathname.split('/').pop().includes('.')) { res.statusCode = 404; res.end('Not found'); return; }
    p = path.join(SRC, 'index.html'); // SPA fallback for client routes
  }
  const ext = path.extname(p).toLowerCase();
  res.setHeader('content-type', MIME[ext] || 'application/octet-stream');
  fs.createReadStream(p).pipe(res);
}
const server = http.createServer(async (req, res) => {
  try {
    res.setHeader('x-powered-by', 'NOIR');
    let pathname;
    try { pathname = decodeURIComponent(new URL(req.url, 'http://x').pathname); } catch { pathname = '/'; }
    const query = new URL(req.url, 'http://x').searchParams;
    const handled = await handleApi(req, res, pathname, query);
    if (!handled) serveStatic(req, res, pathname);
  } catch (e) {
    console.error('[error]', e);
    if (!res.headersSent) { try { fail(res, 500, 'Internal error: ' + (e.message || e)); } catch { /* noop */ } } else res.end();
  }
});
server.listen(PORT, HOST, () => {
  console.log('NOIR app "${spec.name}" → http://' + HOST + ':' + PORT + '  (' + (USE_PG ? 'postgres' : 'file db') + ')');
});
`);
  return L.join('\n');
}
